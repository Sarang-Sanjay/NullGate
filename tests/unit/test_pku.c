/*
 * NullGate — Unit Test: PKU Domain Isolation & Hardware Fault Recovery
 *
 * Verifies:
 *   1. Hardware PKU allocation and initialization.
 *   2. Authorized memory access inside the owning domain.
 *   3. Hardware SEGV_PKUERR trap when an unauthorized compartment accesses memory.
 *   4. Clean recovery via sigsetjmp/siglongjmp and CET-safe call-gate return.
 *   5. Zero raw WRPKRU (0F 01 EF) opcodes in test source.
 */

#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <setjmp.h>
#include <sys/mman.h>
#include <assert.h>
#include <unistd.h>

#include "nullgate.h"
#include "nullgate_abi.h"

#define TEST_STACK_SIZE (64 * 1024)

static sigjmp_buf g_jmpbuf;
static volatile sig_atomic_t g_segv_caught = 0;
static volatile sig_atomic_t g_segv_is_pku = 0;

/*
 * Signal handler for SIGSEGV.
 * Inspects si_code to verify that the fault was generated by PKU (SEGV_PKUERR).
 * Unwinds cleanly via siglongjmp back to the protected block.
 */
static void segv_handler(int sig, siginfo_t *si, void *ucontext)
{
    (void)sig;
    (void)ucontext;

    g_segv_caught = 1;
    if (si && si->si_code == SEGV_PKUERR) {
        g_segv_is_pku = 1;
    }

    siglongjmp(g_jmpbuf, 1);
}

/*
 * Authorized worker in Domain 1:
 * Writes and reads back a canary value from Domain 1 protected memory.
 */
static uint64_t worker_domain_1_authorized(void *arg)
{
    volatile int *ptr = (volatile int *)arg;
    *ptr = 0x1337BEEF;
    if (*ptr != (int)0x1337BEEF) {
        return 0;
    }
    return 1;
}

/*
 * Unauthorized worker in Domain 2:
 * Attempts to read memory assigned to Domain 1.
 * Trapped by hardware PKU with SEGV_PKUERR.
 */
static uint64_t worker_domain_2_unauthorized(void *arg)
{
    volatile int *ptr = (volatile int *)arg;

    if (sigsetjmp(g_jmpbuf, 1) == 0) {
        /*
         * This read MUST fault with SEGV_PKUERR because Domain 2
         * has PKRU_AD set for Domain 1's key.
         */
        volatile int val = *ptr;
        (void)val;
        return 0; /* Should never be reached if hardware PKU works */
    }

    /* Reached via siglongjmp from segv_handler */
    return 0xCAFE;
}

int main(void)
{
    printf("[TEST] Initializing NullGate runtime for PKU isolation test...\n");
    int ret = ng_init();
    if (ret != NG_SUCCESS) {
        fprintf(stderr, "[TEST ERROR] ng_init failed: %s (%d)\n", ng_strerror(ret), ret);
        return 1;
    }

    /* 1. Allocate a page for Domain 1 */
    void *page = mmap(NULL, 4096, PROT_READ | PROT_WRITE,
                      MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    assert(page != MAP_FAILED);

    /* 2. Allocate data stacks for Domain 1 and Domain 2 */
    void *stack1 = mmap(NULL, TEST_STACK_SIZE, PROT_READ | PROT_WRITE,
                        MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    void *stack2 = mmap(NULL, TEST_STACK_SIZE, PROT_READ | PROT_WRITE,
                        MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    assert(stack1 != MAP_FAILED);
    assert(stack2 != MAP_FAILED);

    /* 3. Create Domain 1 and Domain 2 */
    ret = ng_domain_create(1, stack1, TEST_STACK_SIZE);
    assert(ret == NG_SUCCESS);

    ret = ng_domain_create(2, stack2, TEST_STACK_SIZE);
    assert(ret == NG_SUCCESS);

    /* 4. Tag page with Domain 1's PKU key */
    ret = ng_domain_protect(1, page, 4096, PROT_READ | PROT_WRITE);
    assert(ret == NG_SUCCESS);

    /* 5. Install SIGSEGV handler via NullGate signal subsystem */
    ret = ng_signal_register_handler(SIGSEGV, segv_handler);
    assert(ret == NG_SUCCESS);

    /* 6. Enter Domain 1: Authorized write and read */
    printf("[TEST] Executing authorized access in Domain 1...\n");
    uint64_t res1 = ng_enter(1, worker_domain_1_authorized, page);
    assert(res1 == 1);
    (void)res1;
    printf("[TEST] Authorized access in Domain 1 succeeded.\n");

    /* 7. Enter Domain 2: Unauthorized read must trigger SEGV_PKUERR */
    printf("[TEST] Executing unauthorized cross-domain access from Domain 2...\n");
    uint64_t res2 = ng_enter(2, worker_domain_2_unauthorized, page);

    assert(res2 == 0xCAFE);
    (void)res2;
    assert(g_segv_caught == 1);
    assert(g_segv_is_pku == 1);
    printf("[TEST] Hardware PKU violation successfully caught (SEGV_PKUERR).\n");
    printf("[TEST] Clean recovery confirmed across CET call gate.\n");

    /* 7b. CRIT-02 Verification: Domain 2 probe on Domain 1 execution stack must fault with SEGV_PKUERR */
    printf("[TEST] Executing cross-compartment stack probe (Domain 2 -> Domain 1 stack)...\n");
    g_segv_caught = 0;
    g_segv_is_pku = 0;
    uint64_t res_stack = ng_enter(2, worker_domain_2_unauthorized, stack1);
    (void)res_stack;
    assert(res_stack == 0xCAFE);
    assert(g_segv_caught == 1);
    assert(g_segv_is_pku == 1);
    printf("[TEST] Cross-compartment stack isolation verified: Domain 1 stack hardware-protected under PKU!\n");

    /* 8. Cleanup */
    munmap(page, 4096);
    munmap(stack1, TEST_STACK_SIZE);
    munmap(stack2, TEST_STACK_SIZE);

    printf("[TEST] test_pku PASSED.\n");
    return 0;
}
